// Helper function to get random trademarks
export function getRandomTrademarks(count: number): TrademarkMetadata[] {
  const shuffled = [...demoTrademarks].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}

// Helper function to get verified trademarks
export function getVerifiedTrademarks(): TrademarkMetadata[] {
  return demoTrademarks.filter(tm => tm.verified);
}

// Helper function to get trademarks by category
export function getTrademarksByCategory(category: string): TrademarkMetadata[] {
  return demoTrademarks.filter(tm => tm.category === category);
}

// Helper function to search trademarks
export function searchTrademarks(query: string): TrademarkMetadata[] {
  const lowerQuery = query.toLowerCase();
  return demoTrademarks.filter(tm =>
    tm.trademarkName.toLowerCase().includes(lowerQuery) ||
    tm.companyName.toLowerCase().includes(lowerQuery) ||
    tm.description.toLowerCase().includes(lowerQuery) ||
    tm.category.toLowerCase().includes(lowerQuery)
  );
}
