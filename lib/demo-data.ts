// Helper function to get random slogans
export function getRandomSlogans(count: number): SloganMetadata[] {
  const shuffled = [...demoSlogans].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}

// Helper function to get verified slogans
export function getVerifiedSlogans(): SloganMetadata[] {
  return demoSlogans.filter(slogan => slogan.verified);
}

// Helper function to get slogans by category
export function getSlogansByCategory(category: string): SloganMetadata[] {
  return demoSlogans.filter(slogan => slogan.category === category);
}

// Helper function to search slogans
export function searchSlogans(query: string): SloganMetadata[] {
  const lowerQuery = query.toLowerCase();
  return demoSlogans.filter(slogan =>
    slogan.sloganText.toLowerCase().includes(lowerQuery) ||
    slogan.companyName.toLowerCase().includes(lowerQuery) ||
    slogan.description.toLowerCase().includes(lowerQuery) ||
    slogan.category.toLowerCase().includes(lowerQuery)
  );
}

// Backward compatibility
export const getRandomTrademarks = getRandomSlogans;
export const getVerifiedTrademarks = getVerifiedSlogans;
export const getTrademarksByCategory = getSlogansByCategory;
export const searchTrademarks = searchSlogans;
